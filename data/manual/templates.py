def seed():
    init_db()
    existing = {t["name"] for t in get_all_templates()}
    added = updated = 0

    for t in TEMPLATES:
        action = "更新" if t["name"] in existing else "新增"
        if t["name"] in existing:
            updated += 1
        else:
            added += 1

        save_template(
            name=t["name"],
            country=t["country"],
            period=t["period"],
            vector={
                "values": t["vector"],
                "mask": t["mask"],
                "feature_names": VECTOR_LABELS,
                "crisis_type": t["type"],
                "path": t.get("path", {}),
            },
            outcome=t["outcome"]
        )

    print(f"✅ 模板 V2: 新增 {added}, 更新 {updated}, 总计 {len(get_all_templates())}")
    print(f"   危机类型: 债务({sum(1 for t in TEMPLATES if '债务' in t['type'])}), "
          f"货币({sum(1 for t in TEMPLATES if '货币' in t['type'])}), "
          f"通胀({sum(1 for t in TEMPLATES if '通胀' in t['type'])}), "
          f"泡沫({sum(1 for t in TEMPLATES if '泡沫' in t['type'])}), "
          f"冲击({sum(1 for t in TEMPLATES if '冲击' in t['type'])}), "
          f"政策({sum(1 for t in TEMPLATES if '政策' in t['type'])})")


if __name__ == "__main__":
    seed()
