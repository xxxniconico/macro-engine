# LPR 1年期约3.1% (2025)
real_rate = 3.1 - cpi
save("china_real_rate", round(real_rate, 2), today, "computed")
print(f"  ✅ 实际利率 = {real_rate:.1f}% (LPR 3.1% - CPI {cpi}%)")

# 1c. 信用利差 — AAA企业债 vs 国债 (估算)
